// swift -module-cache-path build/swift-module-cache tools/generate_menu_font.swift NotoSansSC-Medium.otf > firmware/AttitudeIndicator/menu_font.h
import Foundation
import CoreGraphics
import CoreText

let characters = "设置安装方向接口在左上右下帧率显示开启关闭按键返回退退出请保持静止正在校准传感器异常重试"
let cell = 24
let source = URL(fileURLWithPath: CommandLine.arguments[1])
let font = CTFontCreateWithGraphicsFont(CGFont(CGDataProvider(url: source as CFURL)!)!, 23, nil, nil)
precondition((CTFontCopyPostScriptName(font) as String) == "NotoSansSC-Medium")
print("""
// Menu glyphs from Noto Sans SC Medium. See MENU_FONT_LICENSE.txt.
// Generated by tools/generate_menu_font.swift.
#pragma once
#include <cstdint>
namespace instrument { namespace menufont {
constexpr int Cell = \(cell);
struct Glyph { char utf8[4]; uint32_t rows[Cell]; };
static constexpr Glyph glyphs[] = {
""")
for scalar in Set(characters.unicodeScalars).sorted(by: { $0.value < $1.value }) {
    var code = UniChar(scalar.value), glyph = CGGlyph()
    precondition(CTFontGetGlyphsForCharacters(font, &code, &glyph, 1), "Missing \(scalar)")
    let box = CTFontGetBoundingRectsForGlyphs(font, .horizontal, &glyph, nil, 1)
    var image = [UInt8](repeating: 0, count: cell * cell)
    image.withUnsafeMutableBytes { bytes in
        let canvas = CGContext(data: bytes.baseAddress, width: cell, height: cell,
            bitsPerComponent: 8, bytesPerRow: cell, space: CGColorSpaceCreateDeviceGray(), bitmapInfo: 0)!
        canvas.setAllowsFontSmoothing(false)
        canvas.setFillColor(gray: 1, alpha: 1)
        var origin = CGPoint(x: (CGFloat(cell) - box.width) / 2 - box.minX, y: 4)
        CTFontDrawGlyphs(font, &glyph, &origin, 1, canvas)
    }
    let rows = (0..<cell).map { y -> UInt32 in
        (0..<cell).reduce(0) { mask, x in mask | (image[y * cell + x] >= 105 ? 1 << x : 0) }
    }
    precondition(rows.contains { $0 != 0 })
    print("{\"\(scalar)\",{\(rows.map { String(format: "0x%06x", $0) }.joined(separator: ","))}},")
}
print("};\n} }")
